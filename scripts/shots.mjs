// 用 Playwright 驱动真实界面跑一遍：问候 → 命令（审批卡）→ 允许 → OpenUI 卡片 → 卡片里提交。
import { chromium } from 'playwright'
const out = '/workspace/dsh-bot/screens'
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/usr/bin/google-chrome' })
const page = await browser.newPage({ viewport: { width: 1400, height: 860 }, deviceScaleFactor: 2 })
page.on('console', m => { if (m.type() === 'error') console.log('console:', m.text()) })
await page.goto('http://127.0.0.1:8787/')
const send = async (text) => { await page.fill('textarea', text); await page.keyboard.press('Enter') }
await page.waitForTimeout(1500)
await send('你好，你能做什么？')
await page.waitForTimeout(250)
await page.screenshot({ path: `${out}/01-streaming.png` })
await page.waitForTimeout(2500)
await page.screenshot({ path: `${out}/02-reply.png` })
await send('帮我运行一条命令')
await page.waitForSelector('.bt-approval', { timeout: 20000 })
await page.waitForTimeout(500)
await page.screenshot({ path: `${out}/03-approval.png` })
await page.click('.bt-approval .bt-q-submit')
await page.waitForTimeout(3500)
await page.locator('.bt-toolcard summary').last().click()
await page.waitForTimeout(400)
await page.screenshot({ path: `${out}/04-tool-result.png` })
await send('给我一张本周任务卡片')
await page.waitForSelector('.ou-card', { timeout: 20000 })
await page.waitForTimeout(2500)
await page.screenshot({ path: `${out}/05-openui.png` })
await page.fill('.ou-input', '先把审批卡做好看一点')
await page.click('.ou-btn')
await page.waitForTimeout(3500)
await page.screenshot({ path: `${out}/06-openui-action.png` })
await browser.close()
console.log('done')
