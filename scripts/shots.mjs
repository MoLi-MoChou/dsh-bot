// v1 端到端：在全新的 DSH_HOME 上，用 Playwright 驱动真实界面走一遍并截图到 ../screens/v1-*.png。
// 模型用 host/mock-llm.mjs（OpenAI 兼容，key 为 sk-mock）；模型配置就在界面里完成。
import { chromium } from 'playwright'
import { writeFileSync } from 'node:fs'
const out = '/workspace/dsh-bot/screens'
const base = process.env.BOT_URL ?? 'http://127.0.0.1:8787/'
const browser = await chromium.launch({ executablePath: process.env.CHROME ?? '/usr/bin/google-chrome' })
const page = await browser.newPage({ viewport: { width: 1400, height: 860 }, deviceScaleFactor: 2 })
const errors = []
page.on('pageerror', e => errors.push(e.message))
page.on('console', m => { if (m.type() === 'error') errors.push(m.text()) })
const shot = async (name) => { await page.waitForTimeout(350); await page.screenshot({ path: `${out}/v1-${name}.png` }); console.log('shot', name) }
const send = async (text) => { await page.fill('textarea[data-composer-input]', text); await page.keyboard.press('Enter') }
const step = (msg) => console.log('·', msg)

await page.goto(base)
await page.waitForSelector('.dsb-welcome', { timeout: 20000 })
await shot('01-empty')

step('还没配模型时发消息 → 明确的错误提示')
await send('你好')
await page.waitForSelector('.dsb-composer-error, .dsb-error-row', { timeout: 20000 })
await shot('02-no-model')

step('设置 → 模型（空）')
await page.click('.dsb-foot-link')
await page.waitForSelector('.dsb-add-row')
await shot('03-models-empty')

step('添加 OpenAI 兼容服务：填地址和 key、获取模型、勾选、测试连接')
await page.click('.dsb-add-row')
await page.waitForSelector('.dsb-profile-form')
await shot('04-models-add-deepseek')
await page.click('.dsb-preset-seg button:nth-of-type(2)')
await page.fill('input[aria-label="名称"]', '本地模拟模型')
await page.fill('input[aria-label="接口地址"]', 'http://127.0.0.1:4010/v1')
await page.fill('.dsb-profile-form input[aria-label="API key"]', 'sk-wrong')
await page.click('text=从接口获取模型列表')
await page.waitForSelector('.bt-error', { timeout: 10000 })
await shot('05-models-fetch-error')
await page.fill('.dsb-profile-form input[aria-label="API key"]', 'sk-mock')
await page.click('text=从接口获取模型列表')
await page.waitForSelector('.bt-provider-found .bt-secret-bot')
await page.click('.bt-provider-found .bt-secret-bot:has-text("mock-chat")')
await page.click('.bt-provider-found .bt-secret-bot:has-text("mock-reasoner")')
await page.click('.dsb-model-item:has-text("mock-chat") button:has-text("图片")')
await page.click('text=测试连接')
await page.waitForSelector('.dsb-test[data-ok]', { timeout: 15000 })
await shot('06-models-test-ok')
await page.click('.dsb-form-actions .bt-fb-primary')
await page.waitForSelector('.bt-provider[data-profile]', { timeout: 15000 })
await page.waitForTimeout(600)
await shot('07-models-list')

step('再加一个 DeepSeek 配置档（多配置档），key 先随便填，不发请求')
await page.click('.dsb-add-row')
await page.fill('.dsb-profile-form input[aria-label="API key"]', 'sk-placeholder-not-tested')
await page.click('.dsb-form-actions .bt-fb-primary')
await page.waitForFunction(() => document.querySelectorAll('.bt-provider[data-profile]').length === 2, null, { timeout: 15000 })
step('默认模型切回本地模拟的 mock-chat')
const value = await page.$eval('.dsb-default-select', s => [...s.options].find(o => o.textContent === 'mock-chat' && o.parentElement.label === '本地模拟模型')?.value)
await page.selectOption('.dsb-default-select', value)
await page.waitForTimeout(800)
await page.click('.bt-provider[data-profile] .bt-secret-summary >> nth=0')
await page.waitForTimeout(400)
await shot('08-models-multi-edit')
await page.click('.bt-settings-close')

step('聊天：流式 + 活动指示')
await send('你好，你能做什么？')
await page.waitForTimeout(450)
await shot('09-streaming')
await page.waitForFunction(() => !document.querySelector('.bt-typing'), null, { timeout: 15000 }).catch(() => {})
await page.waitForTimeout(1800)
await shot('10-reply')

step('命令 → 审批卡 → 允许 → 工具结果')
await send('帮我运行一条命令')
await page.waitForSelector('.bt-approval', { timeout: 20000 })
await shot('11-approval')
await page.click('.bt-approval .bt-q-submit')
await page.waitForFunction(() => document.querySelector('.bt-toolcard summary .bt-toolcard-state')?.textContent === '✓', null, { timeout: 20000 })
await page.waitForTimeout(2500)
await page.locator('.bt-toolcard summary').last().click()
await shot('12-tool-result')

step('OpenUI 卡片：表格、标签、进度、表单、快捷选项')
await send('给我一张本周任务卡片')
await page.waitForSelector('.ou-card', { timeout: 20000 })
await page.waitForTimeout(3500)
await page.fill('.ou-textarea', '先把审批卡做好看一点')
await page.check('.ou-check input')
await page.evaluate(() => document.querySelector('[data-conversation-scroll]').scrollTo(0, 1e9))
await shot('13-openui')
await page.click('.ou-buttons .ou-btn[data-variant=primary]')
await page.waitForTimeout(3500)
await shot('14-openui-action')

step('附件：一张图片 + 一个文本文件')
writeFileSync('/tmp/notes.txt', '会议纪要：周五前完成 v1。\n')
await page.setInputFiles('.dsb-composer input[type=file]', ['/usr/share/icons/hicolor/128x128/apps/google-chrome.png', '/tmp/notes.txt'])
await page.waitForSelector('.dsb-composer-files .dsb-file >> nth=1')
await page.fill('textarea[data-composer-input]', '看看这两个附件')
await shot('15-attach-draft')
await page.keyboard.press('Enter')
await page.waitForSelector('.dsb-urow-files .dsb-file-img', { timeout: 15000 })
await page.waitForTimeout(3000)
await shot('16-attach-sent')

step('新对话 + 会话列表 + 搜索 + 重命名')
await page.click('.bt-side-top button[aria-label="新对话"]')
await page.waitForSelector('.dsb-welcome')
await send('你好')
await page.waitForTimeout(3500)
await page.click('.dsb-conv >> nth=1', { button: 'right' })
await page.click('.bt-menu button:has-text("重命名")')
await page.fill('.bt-agent-edit input', '第一个对话（已重命名）')
await page.keyboard.press('Enter')
await page.waitForTimeout(600)
await shot('17-conversations')
await page.click('.bt-side-top button[aria-label="搜索对话"]')
await page.fill('.dsb-search-input', '重命名')
await shot('18-search')
await page.click('.dsb-conv >> nth=0')
await page.waitForTimeout(1200)
await page.click('.bt-side-top button[aria-label="搜索对话"]')

step('设置：通用、权限、记忆')
await page.click('.dsb-settings')
await page.waitForSelector('.bt-settings')
await shot('19-settings-general')
await page.click('.bt-settings-item:has-text("权限")')
await page.waitForSelector('.bt-seg')
await shot('20-settings-permissions')
await page.click('.bt-settings-item:has-text("记忆")')
await page.waitForSelector('.dsb-mem-text')
await page.fill('.dsb-mem-text >> nth=0', '# 关于我\n\n- 称呼：凯\n- 回复用中文，先给结论\n')
await page.click('.bt-set-section >> nth=0 >> .bt-fb-primary')
await page.waitForSelector('.bt-secret-ok')
await shot('21-settings-memory')
await page.click('.bt-settings-close')

step('暗色主题')
await page.goto(`${base}?theme=dark`)
await page.waitForTimeout(2500)
await shot('22-dark')

console.log(errors.length ? `页面错误：\n${errors.join('\n')}` : '没有页面错误')
await browser.close()
